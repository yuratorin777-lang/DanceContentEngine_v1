/*
 * ==================================================
 * RETRIEVAL CONTEXT RESOLUTION
 * ==================================================
 */

async function readSelectedItemContent(
  candidate: RetrievalCandidate
): Promise<string> {
  const item =
    candidate.item;

  if (!item) {
    return "";
  }

  /*
   * Radar virtual source.
   */
  if (
    item.type ===
    "radar_signal"
  ) {
    const metadata =
      item.radarMetadata
        ? `\nRADAR METADATA:\n${JSON.stringify(
            item.radarMetadata,
            null,
            2
          )}`
        : "";

    return [
      item.title,
      item.purpose,
      ...(item.keywords ||
        []),
      metadata,
    ]
      .filter(Boolean)
      .join("\n");
  }

  const relativePath =
    String(
      item.path || ""
    );

  const absolutePath =
    safeProjectPath(
      relativePath
    );

  if (!absolutePath) {
    return [
      item.title,
      item.purpose,
      ...(item.keywords ||
        []),
    ]
      .filter(Boolean)
      .join("\n");
  }

  try {
    const stat =
      await fs.stat(
        absolutePath
      );

    if (
      !stat.isFile()
    ) {
      return [
        item.title,
        item.purpose,
      ]
        .filter(Boolean)
        .join("\n");
    }

    if (
      stat.size >
      1_500_000
    ) {
      return [
        item.title,
        item.purpose,
      ]
        .filter(Boolean)
        .join("\n");
    }

    return await fs.readFile(
      absolutePath,
      "utf8"
    );
  } catch {
    return [
      item.title,
      item.purpose,
      ...(item.keywords ||
        []),
    ]
      .filter(Boolean)
      .join("\n");
  }
}

async function buildRetrievedContext(
  retrievalPackage: RetrievalPackage,
  includeRadar: boolean
): Promise<{
  filesLoaded: number;
  contextCharacters: number;
  sources: string[];
  context: string;
}> {
  const selected =
    includeRadar
      ? retrievalPackage.selected
      : retrievalPackage.selected.filter(
          candidate =>
            candidate.item?.type !==
            "radar_signal"
        );

  const blocks: string[] =
    [];

  const sources: string[] =
    [];

  let totalCharacters =
    0;

  for (
    const candidate
    of selected
  ) {
    const item =
      candidate.item;

    if (!item) {
      continue;
    }

    if (
      !includeRadar &&
      item.type ===
        "radar_signal"
    ) {
      continue;
    }

    const content =
      await readSelectedItemContent(
        candidate
      );

    if (
      !content.trim()
    ) {
      continue;
    }

    const pathLabel =
      String(
        item.path ||
          item.title ||
          "unknown-source"
      );

    const role =
      String(
        candidate.role ||
          item.sourceRole ||
          item.type ||
          "source"
      );

    const block = `
==================================================
SOURCE: ${pathLabel}
ROLE: ${role}
==================================================

${content}

==================================================
END SOURCE: ${pathLabel}
==================================================
`;

    const nextCharacters =
      totalCharacters +
      block.length;

    if (
      nextCharacters >
      RETRIEVAL_MAX_CHARACTERS
    ) {
      continue;
    }

    blocks.push(
      block
    );

    sources.push(
      pathLabel
    );

    totalCharacters =
      nextCharacters;
  }

  return {
    filesLoaded:
      sources.length,

    contextCharacters:
      totalCharacters,

    sources,

    context:
      blocks.length
        ? blocks.join(
            "\n"
          )
        : `
NO RETRIEVED PROJECT DOCUMENTS WERE LOADED.

Do not invent project-specific information.
State that the required context is missing.
`,
  };
}

