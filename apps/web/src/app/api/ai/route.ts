/*
 * ==================================================
 * PATH SAFETY
 * ==================================================
 */

function safeProjectPath(
  relativePath: string
): string | null {
  const normalized =
    relativePath
      .replace(/\\/g, "/")
      .replace(/^\/+/, "");

  /*
   * Radar virtual references are never
   * directly materialized as files.
   */
  if (
    normalized.includes(
      "#signal-"
    )
  ) {
    return null;
  }

  const absolute =
    path.resolve(
      PROJECT_ROOT,
      normalized
    );

  if (
    absolute !== PROJECT_ROOT &&
    !absolute.startsWith(
      PROJECT_ROOT + path.sep
    )
  ) {
    return null;
  }

  return absolute;
}

