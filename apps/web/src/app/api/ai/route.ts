const GEMINI_API_KEY =
  process.env.GEMINI_API_KEY ||
  "";

async function callAI(
  systemPrompt: string,
  userPrompt: string,
  maxOutputTokens = 2000,
  options: {
    responseMimeType?: string;
    responseSchema?: unknown;
  } = {}
) {
  if (
    !GEMINI_API_KEY
  ) {
    throw new Error(
      "GEMINI_API_KEY is not configured in environment variables."
    );
  }

  const controller =
    new AbortController();

  const timeoutId =
    setTimeout(
      () =>
        controller.abort(),
      60000
    );

  try {
    const url =
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${GEMINI_API_KEY}`;

    const response =
      await fetch(
        url,
        {
          method:
            "POST",

          signal:
            controller.signal,

          headers: {
            "Content-Type":
              "application/json",
          },

          body:
            JSON.stringify({
              systemInstruction: {
                parts: [
                  {
                    text:
                      systemPrompt,
                  },
                ],
              },

              contents: [
                {
                  role:
                    "user",

                  parts: [
                    {
                      text:
                        userPrompt,
                    },
                  ],
                },
              ],

              generationConfig: {
                temperature:
                  0.7,

                maxOutputTokens,

                ...(options.responseMimeType
                  ? {
                      responseMimeType:
                        options.responseMimeType,
                    }
                  : {}),

                ...(options.responseSchema
                  ? {
                      responseSchema:
                        options.responseSchema,
                    }
                  : {}),
              },
            }),
        }
      );

    const raw =
      await response.text();

    if (
      !response.ok
    ) {
      throw new Error(
        `Gemini API error ${response.status}: ${raw.slice(
          0,
          1000
        )}`
      );
    }

    let data: any;

    try {
      data =
        JSON.parse(
          raw
        );
    } catch {
      throw new Error(
        "Gemini API returned invalid JSON."
      );
    }

    const content =
      data?.candidates?.[0]
        ?.content?.parts?.[0]
        ?.text;

    if (
      typeof content !==
        "string" ||
      !content.trim()
    ) {
      throw new Error(
        "Gemini API returned no message content."
      );
    }

    return {
      content,

      model:
        "gemini-2.5-flash",

      usage:
        data?.usageMetadata ||
        null,

      finishReason:
        data?.candidates?.[0]
          ?.finishReason ||
        null,
    };
  } finally {
    clearTimeout(
      timeoutId
    );
  }
}

/*
 * ==================================================
 * GET
 * ==================================================
 */

export async function GET() {
  if (
    !GEMINI_API_KEY
  ) {
    return NextResponse.json({
      ok: false,
      error:
        "GEMINI_API_KEY is missing",
    });
  }

  try {
    const res =
      await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models?key=${GEMINI_API_KEY}`
      );

    const data =
      await res.json();

    const availableModels =
      data?.models
        ? data.models.map(
            (m: any) =>
              m.name.replace(
                "models/",
                ""
              )
          )
        : [];

    return NextResponse.json({
      ok: true,

      service:
        "DanceContentEngine AI Gateway",

      provider:
        "Google Gemini",

      keyExists:
        true,

      availableModels,
    });
  } catch (err: any) {
    return NextResponse.json({
      ok: false,

      error:
        err?.message ||
        "Failed to fetch models from Google",
    });
  }
}

/*
 * ==================================================
 * POST
 * ==================================================
 */

export async function POST(
  request: NextRequest
) {
  const started =
    Date.now();

  try {
    let body: AIRequest;

    try {
      body =
        (await request.json()) as AIRequest;
    } catch {
      return NextResponse.json(
        {
          ok: false,

          error:
            "Invalid or empty JSON body in request.",
        },
        {
          status: 400,
        }
      );
    }

    /*
     * ------------------------------------------------
     * REQUEST
     * ------------------------------------------------
     */

    const task =
      typeof body.task ===
      "string"
        ? body.task.trim()
        : "";

    const requestedPaths =
      Array.isArray(
        body.paths
      )
        ? body.paths.filter(
            item =>
              typeof item ===
              "string"
          )
        : [];

    const requestedChannel =
      typeof body.channel ===
      "string"
        ? body.channel.trim()
        : "";

    const includeRadar =
      body.includeRadar !==
      false;

    const profile:
      ContextProfile =
      body.profile ===
        "CONTENT" ||
      body.profile ===
        "RESEARCH" ||
      body.profile ===
        "ANALYTICS"
        ? body.profile
        : "GENERAL";

    if (!task) {
      return NextResponse.json(
        {
          ok: false,

          error:
            "Task is required.",
        },
        {
          status: 400,
        }
      );
    }

    /*
     * ------------------------------------------------
     * LIBRARIAN → RETRIEVER
     * ------------------------------------------------
     */

    const retrievalSeed =
      buildRetrievalSeed(
        task,
        profile,
        requestedPaths
      );

    const retrievalPackage =
      await buildRetrievalPackage(
        PROJECT_ROOT,
        retrievalSeed,
        {
          maxCharacters:
            RETRIEVAL_MAX_CHARACTERS,

          maxSources:
            RETRIEVAL_MAX_SOURCES,
        }
      ) as RetrievalPackage;

    const retrieved =
      await buildRetrievedContext(
        retrievalPackage,
        includeRadar
      );

    /*
     * ------------------------------------------------
     * OUTPUT CONTRACT
     * ------------------------------------------------
     */

    const outputContract =
      detectWriterOutputContract(
        task
      );

    /*
     * ------------------------------------------------
     * CONTENT STRATEGY
     * ------------------------------------------------
     */

    const strategyContext =
      await loadStrategyContext();

    /*
     * ------------------------------------------------
     * CONTENT PLANNER
     * ------------------------------------------------
     *
     * Important:
     *
     * requestedChannel is passed explicitly.
     *
     * If it exists, Planner MUST use it.
     * If empty, Planner chooses channel according
     * to the strategic documents.
     */

    const planner =
      await callAI(
        buildPlannerSystemPrompt(),

        buildPlannerUserPrompt({
          task,

          profile,

          context:
            retrieved.context,

          strategyContext,

          requestedChannel,
        }),

        6000,

        {
          responseMimeType:
            "application/json",

          responseSchema:
            CONTENT_PLAN_SCHEMA,
        }
      );

    const contentPlan =
      parseContentPlan(
        planner.content
      );

    /*
     * ------------------------------------------------
     * CHANNEL SAFETY CHECK
     * ------------------------------------------------
     *
     * If the request explicitly specified a channel,
     * Planner's answer must match it.
     *
     * This protects the architecture from an LLM
     * silently switching to another channel.
     */

    if (
      requestedChannel &&
      contentPlan.channel !==
        requestedChannel
    ) {
      console.warn(
        "PLANNER CHANNEL OVERRIDE:",
        {
          requestedChannel,
          plannerChannel:
            contentPlan.channel,
        }
      );

      contentPlan.channel =
        requestedChannel;

      contentPlan.constraints =
        [
          ...contentPlan.constraints,

          `Explicit channel requirement: ${requestedChannel}. Planner output was normalized to the requested channel.`,
        ];
    }

    const plannerBrief =
  formatContentPlanForWriter(
    contentPlan
  );

    /*
     * ------------------------------------------------
     * WRITER
     * ------------------------------------------------
     */

    const writerSystemPrompt =
      buildWriterSystemPrompt(
        outputContract
      );

    const systemPrompt =
      `${buildSystemPrompt(
        profile
      )}

==================================================
CONTENT PLANNER EXECUTION LAYER
==================================================

The Content Planner has already converted the user's request into a strategic execution brief.

The selected PRIMARY CHANNEL is authoritative.

The Writer MUST follow the PRIMARY CHANNEL specified in the Content Planner Brief.

Do not silently move the content to another channel.

The Writer must adapt tone, depth, structure, CTA and presentation to the selected channel.

Treat the retrieved project sources as the factual source of truth.

Do not invent information that is absent from the sources.

${plannerBrief}

==================================================
WRITER EXECUTION LAYER
==================================================

${writerSystemPrompt}
`;

    const userPrompt =
      buildWriterUserPrompt({
        task,

        profile,

        context:
          `${plannerBrief}

RETRIEVED PROJECT CONTEXT:

${retrieved.context}`,

        outputContract,
      });

    const ai =
      await callAI(
        systemPrompt,
        userPrompt,
        4000
      );

    /*
     * ------------------------------------------------
     * VALIDATOR
     * ------------------------------------------------
     */

    const validation =
      await validateWriterOutput({
        task,

        outputContract,

        content:
          ai.content,

        context:
          retrieved.context,

        projectRoot:
          PROJECT_ROOT,
      });

    /*
     * ------------------------------------------------
     * RESPONSE
     * ------------------------------------------------
     */

    return NextResponse.json({
      ok: true,

      result:
        ai.content,

      meta: {
        profile,

        requestedChannel:
          requestedChannel ||
          null,

        outputContract,

        contentPlan,

strategyDocuments:
  STRATEGY_FILES,

        plannerModel:
          planner.model,

        model:
          ai.model,

        provider:
          "Google Gemini",

        filesLoaded:
          retrieved.filesLoaded,

        sources:
          retrieved.sources,

        radarIncluded:
          includeRadar,

        contextCharacters:
          retrieved.contextCharacters,

        retrieval: {
          limits:
            retrievalPackage.limits,

          composition:
            retrievalPackage.composition,

          selected:
            retrievalPackage.selected.map(
              candidate => ({
                path:
                  candidate.item?.path ||
                  candidate.item?.title ||
                  "",

                role:
                  candidate.role ||
                  candidate.item?.sourceRole ||
                  candidate.item?.type ||
                  "source",

                relevance:
                  candidate.relevance ??
                  null,

                size:
                  candidate.size ??
                  null,

                reasons:
                  candidate.reasons ||
                  [],
              })
            ),
        },

        durationMs:
          Date.now() -
          started,

        plannerUsage:
          planner.usage,

        usage:
          ai.usage,

        writerFinishReason:
          ai.finishReason,

        validation: {
          status:
            validation.status,

          score:
            validation.score,

          summary:
            validation.summary,

          violations:
            validation.violations,

          rulesLoaded:
            validation.rulesLoaded,
        },
      },
    });
  } catch (error) {
    console.error(
      "AI GATEWAY ERROR:",
      error
    );

    return NextResponse.json(
      {
        ok: false,

        error:
          error instanceof Error
            ? error.message
            : "Unknown AI gateway error.",
      },
      {
        status: 500,
      }
    );
  }
}